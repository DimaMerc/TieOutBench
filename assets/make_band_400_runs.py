#!/usr/bin/env python3
"""
assets/make_band_400_runs.py -- add the series' ledger-palette text band to a generated photograph for the
retrospective post (content/linkedin-post-400-runs-driver.txt). The photograph is AI-generated by the author from
the prompts in content/linkedin-post-400-runs-image-prompts.txt; the band's text is ours. Output is 1080x1350 (4:5).

Run: python assets/make_band_400_runs.py <photo.png> <out.png>
     (uses the tieoutbench env: $USERPROFILE/miniconda3/envs/tieoutbench/python.exe)
"""
import os
import sys
import matplotlib
from PIL import Image, ImageDraw, ImageFont

BG, INK, MUTE, BLUE = "#F3EDE2", "#1C1A17", "#6E675C", "#1E3F66"
W, H, BAND = 1080, 1350, 196
FONTS = os.path.join(os.path.dirname(matplotlib.__file__), "mpl-data", "fonts", "ttf")
SERIF_B = os.path.join(FONTS, "DejaVuSerif-Bold.ttf")
SANS = os.path.join(FONTS, "DejaVuSans.ttf")

LINE1 = "Strong on the call, shaky on the number."
LINE2 = "I expected the opposite."
FOOT = "TieOutBench  ·  evals.finance"


def fit(photo: Image.Image, w: int, h: int) -> Image.Image:
    """Resize to cover w x h, crop from the top (the subject sits in the upper part of every portrait)."""
    scale = max(w / photo.width, h / photo.height)
    im = photo.resize((round(photo.width * scale), round(photo.height * scale)), Image.LANCZOS)
    left = (im.width - w) // 2
    return im.crop((left, 0, left + w, h))


def main(src: str, out: str) -> None:
    photo = Image.open(src).convert("RGB")
    canvas = Image.new("RGB", (W, H), BG)
    canvas.paste(fit(photo, W, H - BAND), (0, 0))
    d = ImageDraw.Draw(canvas)
    y0 = H - BAND
    d.rectangle([0, y0, W, y0 + 2], fill="#D6CDBD")            # hairline between photo and band
    d.rectangle([64, y0 + 34, 64 + 54, y0 + 34 + 7], fill=INK)  # the short ink bar the cards open with
    f1 = ImageFont.truetype(SERIF_B, 37)
    f2 = ImageFont.truetype(SERIF_B, 37)
    f3 = ImageFont.truetype(SANS, 20)
    d.text((64, y0 + 62), LINE1, font=f1, fill=INK)
    d.text((64, y0 + 112), LINE2, font=f2, fill=BLUE)
    tw = d.textlength(FOOT, font=f3)
    d.text((W - 64 - tw, y0 + 125), FOOT, font=f3, fill=MUTE)
    assert d.textlength(LINE1, font=f1) < W - 128, "line 1 overflows"
    canvas.save(out, "PNG", optimize=True)
    print("wrote", out, canvas.size)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
